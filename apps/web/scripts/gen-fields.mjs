// Generates src/lib/api/fields.gen.ts from openapi.json: per-schema field
// metadata (description, units, bounds) the UI needs at runtime for tooltips
// and labels. openapi-typescript only emits descriptions as comments.
import fs from 'node:fs'

const [input = 'openapi.json', output = 'src/lib/api/fields.gen.ts'] = process.argv.slice(2)
const schemas = JSON.parse(fs.readFileSync(input, 'utf8')).components.schemas

const KEYS = ['description', 'units', 'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum']
const out = {}
for (const name of Object.keys(schemas).sort()) {
  const props = schemas[name].properties
  if (!props) continue
  const fields = {}
  for (const prop of Object.keys(props).sort()) {
    // Optional fields wrap their schema in anyOf [..., null]; bounds live on the non-null branch.
    const p = props[prop]
    const branch = p.anyOf?.find((b) => b.type !== 'null') ?? {}
    const meta = {}
    for (const k of KEYS) {
      const v = p[k] ?? branch[k]
      if (v !== undefined) meta[k] = v
    }
    fields[prop] = meta
  }
  out[name] = fields
}

fs.writeFileSync(
  output,
  `// GENERATED by scripts/gen-fields.mjs from openapi.json. Do not edit; run \`make codegen\`.\n\n` +
    `export const fields = ${JSON.stringify(out, null, 2)} as const\n\n` +
    `export type FieldSchema = keyof typeof fields\n`,
)
console.log(`fields → ${output} (${Object.keys(out).length} schemas)`)
